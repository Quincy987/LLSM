    DEFAULT_LANE_WIDTH,
    LANE_CENTER_OFFSET_FACTOR,
    MAX_BRIDGE_WIDTH_TWO_LANES,
    MINIMUM_BRIDGE_WIDTH_FOR_MULTIPLE_LANES,
    MIN_BRIDGE_WIDTH_SINGLE_LANE,
